"""Provider boundary and deterministic offline fixture implementation."""

from __future__ import annotations

from typing import Protocol

from .contracts import Behavior, Contract


class UnsupportedScenario(ValueError):
    """Raised when a provider does not support the requested example."""


class TestProvider(Protocol):
    def generate(self, contract: Contract, behavior: Behavior) -> str:
        """Render a Go test for the given contract behavior."""


class FixtureProvider:
    """Render one fixed, inspectable Go test without a model or network call."""

    def generate(self, contract: Contract, behavior: Behavior) -> str:
        if (
            contract.service != "Jobs"
            or contract.method != "CancelJob"
            or contract.input_type != "CancelJobRequest"
            or behavior.scenario_id != "terminal-no-event"
            or behavior.fixture != "terminal_no_event"
        ):
            raise UnsupportedScenario(
                "fixture provider supports only Jobs.CancelJob / terminal-no-event"
            )
        if "job_id" not in contract.field_names:
            raise UnsupportedScenario("fixture provider requires the job_id input field")

        return '''// Generated by Cartograph's deterministic fixture provider.\n// This is an offline example, not output from a language model.\npackage jobs\n\nimport (\n\t"context"\n\t"testing"\n)\n\nfunc TestCancelJob_TerminalJobDoesNotPublish(t *testing.T) {\n\tservice := NewService(map[string]JobState{"job-123": StateTerminal})\n\terr := service.CancelJob(context.Background(), CancelJobRequest{JobID: "job-123"})\n\tif err != nil {\n\t\tt.Fatalf("CancelJob() error = %v", err)\n\t}\n\tif got := len(service.PublishedEvents()); got != 0 {\n\t\tt.Fatalf("published event count = %d, want 0", got)\n\t}\n}\n'''
